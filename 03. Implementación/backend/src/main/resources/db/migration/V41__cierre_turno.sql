CREATE TABLE `cierre_turno` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `comercio_id` int(11) NOT NULL,
  `turno_fecha` date NOT NULL,
  `horario_id` int(11) NOT NULL,
  `inicio` datetime NOT NULL,
  `fin` datetime NOT NULL,
  `cantidad_pedidos` int(11) NOT NULL,
  `vendido` decimal(14,2) NOT NULL,
  `comision` decimal(14,2) NOT NULL,
  `neto` decimal(14,2) NOT NULL,
  `pendientes_al_cierre` int(11) NOT NULL,
  `fecha_cierre` datetime NOT NULL,
  `email_estado` enum('PENDIENTE','ENVIANDO','ENVIADO','FALLIDO','OMITIDO') NOT NULL DEFAULT 'PENDIENTE',
  `email_intentos` int(11) NOT NULL DEFAULT 0,
  `email_proximo_intento` datetime DEFAULT NULL,
  `email_envio_iniciado` datetime DEFAULT NULL,
  `email_fecha_envio` datetime DEFAULT NULL,
  `email_ultimo_error` varchar(500) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_cierre_turno` (`comercio_id`,`turno_fecha`,`horario_id`),
  KEY `idx_cierre_turno_envio` (`email_estado`,`email_proximo_intento`),
  KEY `idx_cierre_turno_horario` (`horario_id`),
  CONSTRAINT `fk_cierre_turno_comercio` FOREIGN KEY (`comercio_id`) REFERENCES `comercio` (`id`),
  CONSTRAINT `fk_cierre_turno_horario` FOREIGN KEY (`horario_id`) REFERENCES `horario` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
